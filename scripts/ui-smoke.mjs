import assert from 'node:assert/strict'
import { chromium } from 'playwright-core'

const base = process.env.CASA_LIRA_WEB_ORIGIN ?? 'http://127.0.0.1:5173'
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] })
const testTitle = `Objeto de teste ${Date.now()}`
let createdId = null
try {
  const desktop = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await desktop.goto(base)
  await desktop.locator('.catalog-item').first().waitFor()
  const firstTitle = await desktop.locator('.catalog-name').first().innerText()
  await desktop.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true })

  await desktop.locator('.catalog-item').first().click()
  await desktop.getByRole('heading', { name: firstTitle }).waitFor()
  assert.match(await desktop.locator('.detail-price').innerText(), /R\$/)

  await desktop.getByRole('link', { name: 'Painel' }).click()
  await desktop.getByRole('heading', { name: 'Produtos' }).waitFor()
  await desktop.locator('.admin-row').first().waitFor()
  await desktop.screenshot({ path: '.impeccable/review/admin-desktop.png', fullPage: true })
  await desktop.getByRole('link', { name: 'Novo produto' }).click()
  await desktop.locator('#title').fill(testTitle)
  await desktop.locator('#price').fill('0')
  await desktop.getByRole('button', { name: 'Salvar rascunho' }).click()
  await desktop.locator('#price-error').waitFor()
  await desktop.locator('#price').fill('123,45')
  await desktop.getByRole('button', { name: 'Salvar rascunho' }).click()
  await desktop.getByRole('button', { name: 'Publicar produto' }).waitFor()
  const editUrl = desktop.url()
  const id = Number(editUrl.split('/').at(-1))
  assert.ok(Number.isSafeInteger(id) && id > 0)
  createdId = id
  await desktop.getByRole('button', { name: 'Publicar produto' }).click()
  await desktop.getByText('Produto publicado no catálogo.').waitFor()
  await desktop.goto(base)
  await desktop.locator('.catalog-item').first().waitFor()
  assert.match(await desktop.locator('.catalog-item').first().innerText(), new RegExp(testTitle))
  await desktop.goto(`${base}/products/${id}`)
  await desktop.getByRole('heading', { name: testTitle }).waitFor()
  await desktop.goto(editUrl)
  await desktop.locator('#title').fill(`${testTitle} editado`)
  await desktop.getByRole('button', { name: 'Salvar alterações' }).click()
  await desktop.getByText('Alterações salvas e visíveis no catálogo.').waitFor()
  await desktop.goto(`${base}/products/${id}`)
  await desktop.getByRole('heading', { name: `${testTitle} editado` }).waitFor()
  await desktop.goto(editUrl)
  await desktop.getByRole('button', { name: 'Retirar de publicação' }).click()
  await desktop.getByText('Produto retirado do catálogo.').waitFor()
  await desktop.goto(`${base}/products/${id}`)
  await desktop.getByRole('heading', { name: 'Produto não encontrado.' }).waitFor()
  await desktop.goto(`${base}/admin`)
  const row = desktop.locator('.admin-row').filter({ hasText: `${testTitle} editado` })
  await row.waitFor()
  desktop.once('dialog', dialog => dialog.accept())
  await row.getByRole('button', { name: 'Excluir' }).click()
  await row.waitFor({ state: 'detached' })
  createdId = null

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 })
  await mobile.goto(base)
  await mobile.locator('.catalog-item').first().waitFor()
  await mobile.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true })
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await mobile.getByRole('link', { name: 'Painel' }).click()
  await mobile.getByRole('heading', { name: 'Produtos' }).waitFor()
  await mobile.locator('.admin-row').first().waitFor()
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  await mobile.screenshot({ path: '.impeccable/review/admin-mobile.png', fullPage: true })
  await mobile.getByRole('link', { name: 'Novo produto' }).click()
  await mobile.locator('#title').waitFor()
  await mobile.screenshot({ path: '.impeccable/review/form-mobile.png', fullPage: true })
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
  console.log('UI smoke: catálogo, detalhe, validação, CRUD, publicação e celular passaram.')
} finally {
  if (createdId) await fetch(`${base}/api/admin/products/${createdId}`, { method: 'DELETE' }).catch(() => {})
  await browser.close()
}
